// Refreshes js/errors-data.js from Twilio's public error catalog.
// Twilio doesn't send CORS headers for this file, so the page ships a snapshot.
// Usage: node scripts/update-errors.mjs
import { writeFile } from 'node:fs/promises';

const SRC = 'https://www.twilio.com/docs/api/errors/twilio-error-codes.json';
const OUT = new URL('../js/errors-data.js', import.meta.url);

const res = await fetch(SRC);
if (!res.ok) throw new Error(`${SRC} → HTTP ${res.status}`);
const all = await res.json();

const clean = (s) => (s || '').trim() || undefined;
const rows = all
  .filter(e => e.code && e.message)
  .map(e => ({ c: e.code, m: e.message.trim(), p: clean(e.product), l: clean(e.log_level),
               d: clean(e.description), ca: clean(e.causes), s: clean(e.solutions),
               u: (e.last_updated || '').slice(0, 10) || undefined }))
  .sort((a, b) => a.c - b.c);

const snapshot = new Date().toISOString().slice(0, 10);
await writeFile(OUT, `// Generated by scripts/update-errors.mjs from ${SRC}\n` +
  `window.TWILIO_ERRORS = ${JSON.stringify({ snapshot, rows })};\n`);
console.log(`Wrote ${rows.length} error codes (snapshot ${snapshot})`);
